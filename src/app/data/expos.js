/**
 * Retrieve expos with eventStart on/after today, sorted by eventStart.
 * @returns {Array} Future expos sorted by eventStart (ascending).
 */
export function getExpos() {
  const today = new Date();
  today.setHours(0, 0, 0, 0);

  return [...expos]
    .filter((e) => new Date(e.eventEnd) > today)
    .sort((a, b) => new Date(a.eventStart) - new Date(b.eventStart));
}

/**
 * Retrieve a single expo by slug.
 * @param {string} slug - The expo slug (route param).
 * @returns {Object|null} Expo object or null if not found.
 */
export function getExpoBySlug(slug) {
  return expos.find((e) => e.slug === slug) || null;
}

/**
 * Retrieve all upcoming expos (status: 'upcoming').
 * @returns {Array} Upcoming expos sorted by eventStart.
 */
export function getUpcomingExpos() {
  return getExpos().filter((e) => e.status === 'upcoming');
}

/**
 * Retrieve all featured expos.
 * @returns {Array} Featured expos sorted by eventStart.
 */
export function getFeaturedExpos() {
  return getExpos().filter((e) => e.featured && e.status === 'upcoming');
}
